using System.Text;
using Stoop.Domain;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Design;
using NetTopologySuite.Geometries;

namespace Stoop.Infrastructure.Persistence;

public sealed class AppDbContext(DbContextOptions<AppDbContext> options) : DbContext(options)
{
    public DbSet<User> Users => Set<User>();
    public DbSet<ExternalIdentity> ExternalIdentities => Set<ExternalIdentity>();
    public DbSet<Community> Communities => Set<Community>();
    public DbSet<CommunityMember> CommunityMembers => Set<CommunityMember>();
    public DbSet<Conversation> Conversations => Set<Conversation>();
    public DbSet<ConversationMember> ConversationMembers => Set<ConversationMember>();
    public DbSet<Message> Messages => Set<Message>();
    public DbSet<AuditLogEntry> AuditLog => Set<AuditLogEntry>();
    public DbSet<NostrChallenge> NostrChallenges => Set<NostrChallenge>();

    /// <summary>The same expression as in Sql/001_init.sql (the database generates the column).</summary>
    private const string LocationPointSql =
        "CASE WHEN latitude IS NULL OR longitude IS NULL THEN NULL ELSE ST_SetSRID(ST_MakePoint(longitude, latitude), 4326) END";

    protected override void OnModelCreating(ModelBuilder mb)
    {
        mb.HasPostgresExtension("postgis");
        mb.HasPostgresExtension("pg_trgm");

        mb.Entity<User>(e =>
        {
            e.ToTable("users");
            e.HasKey(x => x.Id);
            e.Property(x => x.DisplayName).HasMaxLength(40);
            e.Property(x => x.Email).HasMaxLength(254);
            e.Property(x => x.PrimaryNostrPublicKey).HasMaxLength(64);
            e.Property(x => x.Status).HasConversion<string>();
        });

        mb.Entity<ExternalIdentity>(e =>
        {
            e.ToTable("external_identities");
            e.HasKey(x => x.Id);
            e.Property(x => x.Provider).HasMaxLength(32);
            e.Property(x => x.ExternalIdentifier).HasMaxLength(128);
            e.HasOne<User>().WithMany().HasForeignKey(x => x.UserId);
        });

        mb.Entity<Community>(e =>
        {
            e.ToTable("communities");
            e.HasKey(x => x.Id);
            e.Ignore(x => x.HasLocation);
            e.Property(x => x.Name).HasMaxLength(80);
            e.Property(x => x.Slug).HasMaxLength(80);
            e.Property(x => x.Description).HasMaxLength(2000);
            e.Property(x => x.Topic).HasMaxLength(60);
            e.Property(x => x.CoverImageUrl).HasMaxLength(500);
            e.Property(x => x.LocationName).HasMaxLength(120);
            e.Property(x => x.PriceAmount).HasColumnType("numeric(12,2)");
            e.Property(x => x.PriceCurrency).HasMaxLength(3);
            e.Property(x => x.Category).HasConversion<string>();
            e.Property(x => x.Visibility).HasConversion<string>();
            e.Property(x => x.AccessMode).HasConversion<string>();
            e.Property(x => x.PricingMode).HasConversion<string>();
            e.Property(x => x.Status).HasConversion<string>();
            // PostGIS point, generated by the database from latitude/longitude. Shadow property:
            // the domain model stays free of NetTopologySuite types; queries use EF.Property<Point>(c, "LocationPoint").
            e.Property<Point>("LocationPoint")
                .HasColumnType("geometry(Point,4326)")
                .HasComputedColumnSql(LocationPointSql, stored: true);
            e.HasOne<User>().WithMany().HasForeignKey(x => x.CreatedByUserId);
        });

        mb.Entity<CommunityMember>(e =>
        {
            e.ToTable("community_members");
            e.HasKey(x => new { x.CommunityId, x.UserId });
            e.Property(x => x.Role).HasConversion<string>();
            e.Property(x => x.Status).HasConversion<string>();
            e.HasOne<Community>().WithMany().HasForeignKey(x => x.CommunityId);
            e.HasOne<User>().WithMany().HasForeignKey(x => x.UserId);
            e.HasOne<User>().WithMany().HasForeignKey(x => x.InvitedByUserId);
        });

        mb.Entity<Conversation>(e =>
        {
            e.ToTable("conversations");
            e.HasKey(x => x.Id);
            e.Property(x => x.DirectKey).HasMaxLength(80);
            e.Property(x => x.Type).HasConversion<string>();
            e.Property(x => x.Status).HasConversion<string>();
            e.HasOne<Community>().WithMany().HasForeignKey(x => x.CommunityId);
        });

        mb.Entity<ConversationMember>(e =>
        {
            e.ToTable("conversation_members");
            e.HasKey(x => new { x.ConversationId, x.UserId });
            e.Property(x => x.Status).HasConversion<string>();
            e.HasOne<Conversation>().WithMany().HasForeignKey(x => x.ConversationId);
            e.HasOne<User>().WithMany().HasForeignKey(x => x.UserId);
        });

        mb.Entity<Message>(e =>
        {
            e.ToTable("messages");
            e.HasKey(x => x.Id);
            e.Property(x => x.Status).HasConversion<string>();
            e.HasOne<Conversation>().WithMany().HasForeignKey(x => x.ConversationId);
            e.HasOne<User>().WithMany().HasForeignKey(x => x.SenderUserId);
            e.HasOne<User>().WithMany().HasForeignKey(x => x.DeletedByUserId);
        });

        mb.Entity<AuditLogEntry>(e =>
        {
            e.ToTable("audit_log");
            e.HasKey(x => x.Id);
            e.Property(x => x.Action).HasMaxLength(64);
        });

        mb.Entity<NostrChallenge>(e =>
        {
            e.ToTable("nostr_challenges");
            e.HasKey(x => x.Value);
            e.Property(x => x.Value).HasMaxLength(64);
            e.Property(x => x.BoundPublicKey).HasMaxLength(64);
            e.Property(x => x.Purpose).HasConversion<string>();
        });

        ApplySnakeCaseColumns(mb);
    }

    // Matches the column names in Sql/001_init.sql without needing an extra naming-convention package.
    private static void ApplySnakeCaseColumns(ModelBuilder mb)
    {
        foreach (var entity in mb.Model.GetEntityTypes())
            foreach (var property in entity.GetProperties())
                property.SetColumnName(ToSnake(property.Name));
    }

    internal static string ToSnake(string name)
    {
        var sb = new StringBuilder(name.Length + 4);
        for (var i = 0; i < name.Length; i++)
        {
            var c = name[i];
            if (char.IsUpper(c) && i > 0 && (char.IsLower(name[i - 1]) || char.IsDigit(name[i - 1]))) sb.Append('_');
            sb.Append(char.ToLowerInvariant(c));
        }
        return sb.ToString();
    }
}

/// <summary>Lets `dotnet ef` create the context at design time: set ConnectionStrings__Default.</summary>
public sealed class DesignTimeDbContextFactory : IDesignTimeDbContextFactory<AppDbContext>
{
    public AppDbContext CreateDbContext(string[] args)
    {
        var cs = Environment.GetEnvironmentVariable("ConnectionStrings__Default")
            ?? "Host=localhost;Port=5432;Database=stoop;Username=stoop;Password=change-me";
        var options = new DbContextOptionsBuilder<AppDbContext>()
            .UseNpgsql(cs, o => o.UseNetTopologySuite())
            .Options;
        return new AppDbContext(options);
    }
}
