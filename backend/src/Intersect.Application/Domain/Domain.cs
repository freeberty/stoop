using System.Text.Json.Serialization;
namespace Intersect.Domain;

// ---------------------------------------------------------------- enums

[JsonConverter(typeof(JsonStringEnumConverter))]
public enum Visibility { Public = 0, Private = 1, Unlisted = 2 }

[JsonConverter(typeof(JsonStringEnumConverter))]
public enum AccessMode { Open = 0, ApprovalRequired = 1, InvitationOnly = 2, Verified = 3 }

[JsonConverter(typeof(JsonStringEnumConverter))]
public enum PricingMode { Free = 0, Paid = 1 }

[JsonConverter(typeof(JsonStringEnumConverter))]
public enum CommunityStatus { Draft = 0, Active = 1, Archived = 2, Expired = 3 }

[JsonConverter(typeof(JsonStringEnumConverter))]
public enum CommunityCategory
{
    DigitalNomads, Alumni, Conference, Photography, Gaming, Technology,
    Arts, Music, Sports, Outdoors, Food, Travel, History, Social, Other
}

[JsonConverter(typeof(JsonStringEnumConverter))]
public enum MemberRole { Member = 0, Admin = 1, Owner = 2 }

/// <summary>
/// Pending = user asked, admin must approve. Invited = admin invited, user must accept.
/// AwaitingPayment = all other rules satisfied, payment outstanding (paid communities).
/// </summary>
[JsonConverter(typeof(JsonStringEnumConverter))]
public enum MemberStatus { Pending = 0, Invited = 1, AwaitingPayment = 2, Active = 3, Left = 4, Removed = 5, Banned = 6 }

[JsonConverter(typeof(JsonStringEnumConverter))]
public enum UserStatus { Active = 0, Suspended = 1 }

[JsonConverter(typeof(JsonStringEnumConverter))]
public enum ConversationType { Community = 0, Direct = 1 }

[JsonConverter(typeof(JsonStringEnumConverter))]
public enum ConversationStatus { Active = 0, Closed = 1 }

[JsonConverter(typeof(JsonStringEnumConverter))]
public enum ConversationMemberStatus { Active = 0, Removed = 1 }

[JsonConverter(typeof(JsonStringEnumConverter))]
public enum MessageStatus { Active = 0, Deleted = 1 }

[JsonConverter(typeof(JsonStringEnumConverter))]
public enum ChallengePurpose { Login = 0, Link = 1 }

// ---------------------------------------------------------------- entities

public class User
{
    public Guid Id { get; set; }
    public string DisplayName { get; set; } = "";
    /// <summary>Lower-cased. Optional (Nostr-only accounts have none).</summary>
    public string? Email { get; set; }
    public string? PasswordHash { get; set; }
    /// <summary>Hex x-only public key of the first/primary linked Nostr identity.</summary>
    public string? PrimaryNostrPublicKey { get; set; }
    public DateTimeOffset CreatedAt { get; set; }
    public UserStatus Status { get; set; }
}

public class ExternalIdentity
{
    public Guid Id { get; set; }
    public Guid UserId { get; set; }
    public string Provider { get; set; } = "";            // "nostr"
    public string ExternalIdentifier { get; set; } = "";  // hex pubkey
    public DateTimeOffset LinkedAt { get; set; }

    public const string NostrProvider = "nostr";
}

public class Community
{
    public Guid Id { get; set; }
    public string Name { get; set; } = "";
    public string Slug { get; set; } = "";
    public string Description { get; set; } = "";
    public CommunityCategory Category { get; set; }
    public string? Topic { get; set; }
    public string? CoverImageUrl { get; set; }

    // Location is optional. LocationPoint (PostGIS geometry(Point,4326)) is generated by the
    // database from these two columns; LocationArea is a nullable future-ready geometry column.
    public string? LocationName { get; set; }
    public double? Latitude { get; set; }
    public double? Longitude { get; set; }

    /// <summary>Context dates: the period the community is ABOUT (not creation/expiry).</summary>
    public DateOnly? ContextStartDate { get; set; }
    public DateOnly? ContextEndDate { get; set; }

    public DateTimeOffset CreatedAt { get; set; }
    /// <summary>When the community stops being active. Distinct from the context dates.</summary>
    public DateTimeOffset? ExpiresAt { get; set; }

    public Visibility Visibility { get; set; }
    public AccessMode AccessMode { get; set; }
    public PricingMode PricingMode { get; set; }
    public decimal? PriceAmount { get; set; }
    public string? PriceCurrency { get; set; }
    public CommunityStatus Status { get; set; }
    public Guid CreatedByUserId { get; set; }
    public int MemberCount { get; set; }

    public bool HasLocation => Latitude.HasValue && Longitude.HasValue;
}

public class CommunityMember
{
    public Guid CommunityId { get; set; }
    public Guid UserId { get; set; }
    public MemberRole Role { get; set; }
    public MemberStatus Status { get; set; }
    public Guid? InvitedByUserId { get; set; }
    public DateTimeOffset? RequestedAt { get; set; }
    public DateTimeOffset? JoinedAt { get; set; }
    public DateTimeOffset UpdatedAt { get; set; }
    /// <summary>Paid communities: access valid until this instant.</summary>
    public DateTimeOffset? PaidUntil { get; set; }
}

public class Conversation
{
    public Guid Id { get; set; }
    public ConversationType Type { get; set; }
    public Guid? CommunityId { get; set; }
    /// <summary>Direct conversations only: "minGuid:maxGuid" (unique).</summary>
    public string? DirectKey { get; set; }
    public DateTimeOffset CreatedAt { get; set; }
    public ConversationStatus Status { get; set; }
}

public class ConversationMember
{
    public Guid ConversationId { get; set; }
    public Guid UserId { get; set; }
    public DateTimeOffset JoinedAt { get; set; }
    public DateTimeOffset? LastReadAt { get; set; }
    public ConversationMemberStatus Status { get; set; }
}

public class Message
{
    public Guid Id { get; set; }
    public Guid ConversationId { get; set; }
    public Guid SenderUserId { get; set; }
    public string Content { get; set; } = "";
    public DateTimeOffset CreatedAt { get; set; }
    public DateTimeOffset? EditedAt { get; set; }
    public DateTimeOffset? DeletedAt { get; set; }
    public Guid? DeletedByUserId { get; set; }
    public MessageStatus Status { get; set; }
}

public class AuditLogEntry
{
    public Guid Id { get; set; }
    public DateTimeOffset At { get; set; }
    public Guid? ActorUserId { get; set; }
    public string Action { get; set; } = "";
    public Guid? CommunityId { get; set; }
    public Guid? TargetUserId { get; set; }
    public string? Details { get; set; }
}

public class NostrChallenge
{
    public string Value { get; set; } = "";
    public ChallengePurpose Purpose { get; set; }
    /// <summary>If set, only an event signed by this key can consume the challenge.</summary>
    public string? BoundPublicKey { get; set; }
    /// <summary>Link challenges are tied to the authenticated user who requested them.</summary>
    public Guid? UserId { get; set; }
    public DateTimeOffset CreatedAt { get; set; }
    public DateTimeOffset ExpiresAt { get; set; }
    public DateTimeOffset? ConsumedAt { get; set; }
}
